// Command pricing refreshes data/pricing/aws-<region>.yaml from the AWS Price List API
// (on-demand Linux, shared tenancy) and the EC2 spot price history (24 h average). It only
// reads from AWS and is never run in CI.
//
//	go run ./hack/pricing --region us-east-1 --out data/pricing/aws-us-east-1.yaml
package main

import (
	"context"
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"sort"
	"strconv"
	"time"

	"github.com/aws/aws-sdk-go-v2/aws"
	"github.com/aws/aws-sdk-go-v2/config"
	"github.com/aws/aws-sdk-go-v2/service/ec2"
	ec2types "github.com/aws/aws-sdk-go-v2/service/ec2/types"
	"github.com/aws/aws-sdk-go-v2/service/pricing"
	pricingtypes "github.com/aws/aws-sdk-go-v2/service/pricing/types"
	"sigs.k8s.io/yaml"

	"github.com/hermeto/aibox/internal/cost"
)

func main() {
	region := flag.String("region", "us-east-1", "AWS region to price")
	out := flag.String("out", "", "price table to update (default data/pricing/aws-<region>.yaml)")
	flag.Parse()
	if *out == "" {
		*out = "data/pricing/aws-" + *region + ".yaml"
	}
	if err := run(context.Background(), *region, *out); err != nil {
		fmt.Fprintln(os.Stderr, "pricing:", err)
		os.Exit(1)
	}
}

func run(ctx context.Context, region, out string) error {
	table, err := cost.LoadTable(".", region)
	if err != nil {
		return err
	}
	cfg, err := config.LoadDefaultConfig(ctx, config.WithRegion(region))
	if err != nil {
		return err
	}
	// The Price List API is served from us-east-1.
	pc := pricing.NewFromConfig(cfg, func(o *pricing.Options) { o.Region = "us-east-1" })
	ec := ec2.NewFromConfig(cfg)
	types := make([]string, 0, len(table.Instances))
	for t := range table.Instances {
		types = append(types, t)
	}
	sort.Strings(types)
	for _, t := range types {
		p := table.Instances[t]
		od, err := onDemand(ctx, pc, region, t)
		if err != nil {
			return fmt.Errorf("%s on-demand: %w", t, err)
		}
		spot, err := spotAverage(ctx, ec, t)
		if err != nil {
			return fmt.Errorf("%s spot: %w", t, err)
		}
		p.OnDemand, p.Spot = od, spot
		table.Instances[t] = p
		fmt.Printf("%-14s on-demand %.4f spot %.4f\n", t, od, spot)
	}
	table.Source = "AWS Price List API (on-demand, Linux, shared tenancy) and EC2 spot price history (24 h average)"
	table.LastUpdated = time.Now().UTC().Format("2006-01-02")
	table.Verified = true
	data, err := yaml.Marshal(table)
	if err != nil {
		return err
	}
	header := "# AIBox price table — USD per hour. Generated by hack/pricing; edit only fixed items\n# and capacityBlock prices by hand.\n"
	return os.WriteFile(out, append([]byte(header), data...), 0o600)
}

func onDemand(ctx context.Context, pc *pricing.Client, region, instanceType string) (float64, error) {
	filter := func(field, value string) pricingtypes.Filter {
		return pricingtypes.Filter{Type: pricingtypes.FilterTypeTermMatch, Field: aws.String(field), Value: aws.String(value)}
	}
	res, err := pc.GetProducts(ctx, &pricing.GetProductsInput{
		ServiceCode: aws.String("AmazonEC2"),
		Filters: []pricingtypes.Filter{
			filter("regionCode", region), filter("instanceType", instanceType), filter("operatingSystem", "Linux"),
			filter("tenancy", "Shared"), filter("preInstalledSw", "NA"), filter("capacitystatus", "Used"),
		},
	})
	if err != nil {
		return 0, err
	}
	for _, item := range res.PriceList {
		var doc struct {
			Terms struct {
				OnDemand map[string]struct {
					PriceDimensions map[string]struct {
						PricePerUnit map[string]string `json:"pricePerUnit"`
					} `json:"priceDimensions"`
				} `json:"OnDemand"`
			} `json:"terms"`
		}
		if err := json.Unmarshal([]byte(item), &doc); err != nil {
			return 0, err
		}
		for _, term := range doc.Terms.OnDemand {
			for _, dim := range term.PriceDimensions {
				if v, err := strconv.ParseFloat(dim.PricePerUnit["USD"], 64); err == nil && v > 0 {
					return v, nil
				}
			}
		}
	}
	return 0, fmt.Errorf("no on-demand price found")
}

func spotAverage(ctx context.Context, ec *ec2.Client, instanceType string) (float64, error) {
	p := ec2.NewDescribeSpotPriceHistoryPaginator(ec, &ec2.DescribeSpotPriceHistoryInput{
		InstanceTypes:       []ec2types.InstanceType{ec2types.InstanceType(instanceType)},
		ProductDescriptions: []string{"Linux/UNIX"},
		StartTime:           aws.Time(time.Now().Add(-24 * time.Hour)),
	})
	var sum float64
	var n int
	for p.HasMorePages() {
		page, err := p.NextPage(ctx)
		if err != nil {
			return 0, err
		}
		for _, h := range page.SpotPriceHistory {
			if v, err := strconv.ParseFloat(aws.ToString(h.SpotPrice), 64); err == nil {
				sum += v
				n++
			}
		}
	}
	if n == 0 {
		return 0, nil // not offered as spot (e.g. p5 via Capacity Blocks only)
	}
	return float64(int(sum/float64(n)*10000)) / 10000, nil
}
