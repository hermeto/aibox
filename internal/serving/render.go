// Package serving renders a profile's model servers from the model catalog: one KServe
// LLMInferenceService per enabled, served model (ADR-0002). The rendered servers override the
// `main` container of KServe's default template with AIBox's runtime image, command, flags,
// probes, warm-up hook, drain settings, resources and placement.
package serving

import (
	"bytes"
	_ "embed"
	"fmt"
	"sort"
	"strconv"
	"strings"

	"sigs.k8s.io/yaml"

	"github.com/hermeto/aibox/internal/gpu"
	"github.com/hermeto/aibox/internal/models"
	"github.com/hermeto/aibox/internal/profile"
)

// Header is written at the top of generated files.
const Header = "# Generated by `aibox render serving` from models/catalog.yaml and profiles/%s.yaml — do not edit.\n# Regenerate with `make generate`; CI fails on drift.\n"

// Pinned runtime images (specs/008-inference-runtime/research.md).
const (
	VLLMImage      = "vllm/vllm-openai:v0.33.0@sha256:d825baf9ce4b1b6bfc5ecc7b79880c7e6748c65a72d697ce3d47607aafa84c6e"
	SGLangImage    = "lmsysorg/sglang:v0.5.23@sha256:f832b5c39559c9caa900b22ad37c76fcce66470676855c42052102c537812f1f"
	SimulatorImage = "ghcr.io/llm-d/llm-d-inference-sim:v1.1.0@sha256:012cf6aa414cfbb910743274458dd62c0c0a9d469eb2ba2b28fd5b963516447d"
)

// Names shared with the platform and the 004 IAM module (Pod Identity for model-server).
const (
	Namespace      = "aibox-serving"
	Port           = 8000
	ServiceAccount = "model-server"
	// RunConfigMap holds run data the CLI writes at bring-up (weightsBucket, runId, region).
	RunConfigMap   = "aibox-run"
	FetchConfigMap = "model-fetch-scripts"
	TokenSecret    = "hf-token"
	runtimeUID     = 1000
	simulatorUID   = 65532
	drainMargin    = 20 // seconds of the grace period left for preStop and exit
)

// GPU sizing per GPU of tensor parallelism (documented in the spec clarifications).
const (
	cpuPerGPU    = 4
	memGiPerGPU  = 16
	shmGiPerGPU  = 8
	gpuResource  = "nvidia.com/gpu"
	simulatorGPU = "gpu-sim"
)

//go:embed warmup.py
var warmupScript string

// Render returns the serving manifests for the profile's enabled, served catalog models.
func Render(p *profile.Profile, c *models.Catalog) ([]byte, error) {
	sel, err := c.Select(p.Metadata.Name, false, nil)
	if err != nil {
		return nil, err
	}
	sort.Slice(sel, func(i, j int) bool { return sel[i].ID < sel[j].ID })
	var (
		objs   []any
		served []*models.Model
		fetch  bool
	)
	for i := range sel {
		m := &sel[i]
		if !m.Served() {
			continue
		}
		obj, err := Service(p, m)
		if err != nil {
			return nil, err
		}
		objs = append(objs, obj)
		served = append(served, m)
		fetch = fetch || m.LoadMethod == "nvme-cache"
	}
	// Gateway routing (feature 009): per-model backends, one route, the profile's rate limits.
	for _, m := range served {
		objs = append(objs, routing(m)...)
	}
	if len(served) > 0 {
		objs = append(objs, route(served), rateLimits(p))
	}
	if fetch {
		cm, err := fetchScripts()
		if err != nil {
			return nil, err
		}
		objs = append([]any{cm}, objs...)
	}
	var out bytes.Buffer
	fmt.Fprintf(&out, Header, p.Metadata.Name)
	for _, o := range objs {
		b, err := yaml.Marshal(o)
		if err != nil {
			return nil, err
		}
		out.WriteString("---\n")
		out.Write(b)
	}
	return out.Bytes(), nil
}

// Name is the Kubernetes name of a model's server (dots are not valid in pod hostnames).
func Name(modelID string) string { return strings.ReplaceAll(modelID, ".", "-") }

// Service returns the LLMInferenceService of one model.
func Service(p *profile.Profile, m *models.Model) (map[string]any, error) {
	if err := place(p, m); err != nil {
		return nil, err
	}
	var (
		container map[string]any
		pod       = map[string]any{}
		err       error
	)
	switch m.Runtime {
	case "vllm":
		container, err = vllm(m)
	case "sglang":
		container, err = sglang(m)
	case "simulator":
		container = simulator(m)
	default:
		err = fmt.Errorf("unknown runtime %q", m.Runtime)
	}
	if err != nil {
		return nil, fmt.Errorf("model %s: %w", m.ID, err)
	}
	uid := runtimeUID
	if m.Runtime == "simulator" {
		uid = simulatorUID
	} else {
		addGPU(m, container, pod)
		addWarmup(m, container)
		if err := addWeights(m, container, pod); err != nil {
			return nil, fmt.Errorf("model %s: %w", m.ID, err)
		}
	}
	pod["serviceAccountName"] = ServiceAccount
	pod["terminationGracePeriodSeconds"] = m.GracePeriod()
	pod["securityContext"] = map[string]any{
		"runAsNonRoot": true, "runAsUser": uid, "runAsGroup": uid, "fsGroup": uid,
		"seccompProfile": map[string]any{"type": "RuntimeDefault"},
	}
	pod["nodeSelector"] = map[string]any{gpu.ClassLabel: m.MinGPUClass}
	pod["tolerations"] = []any{map[string]any{"key": gpu.GPUTaintKey, "operator": "Exists", "effect": "NoSchedule"}}
	pod["containers"] = []any{container}

	labels := map[string]any{
		"aibox.dev/model":           m.ID,
		"aibox.dev/runtime":         m.Runtime,
		"app.kubernetes.io/part-of": "aibox",
	}
	// `spec.labels` is copied onto the generated Deployment and its pod template. KServe
	// shares that label map with the Deployment selector, so overriding the reserved
	// `app.kubernetes.io/part-of` key hides the Deployment from the controller's cache (which
	// filters child resources by part-of=llminferenceservice) and every reconcile then fails
	// with "deployment already exists". Keep only AIBox's own keys here; the pods still get
	// `aibox.dev/model`/`aibox.dev/runtime` for the gateway and the PodMonitor.
	specLabels := map[string]any{
		"aibox.dev/model":   m.ID,
		"aibox.dev/runtime": m.Runtime,
	}
	return map[string]any{
		"apiVersion": "serving.kserve.io/v1alpha2",
		"kind":       "LLMInferenceService",
		"metadata": map[string]any{
			"name":      Name(m.ID),
			"namespace": Namespace,
			"labels":    labels,
			"annotations": map[string]any{
				"aibox.dev/load-method": m.LoadMethod,
				"aibox.dev/revision":    m.Source.Revision,
			},
		},
		"spec": map[string]any{
			// Provenance only: AIBox loads the weights itself (storage initializer disabled).
			"model":              map[string]any{"uri": modelURI(m), "name": m.ID},
			"storageInitializer": map[string]any{"enabled": false},
			"replicas":           1,
			"parallelism":        map[string]any{"tensor": m.TensorParallelSize},
			"labels":             specLabels,
			"template":           pod,
		},
	}, nil
}

func modelURI(m *models.Model) string {
	if m.Mirrorable() {
		return "hf://" + m.Source.Repo
	}
	return "hf://simulator/" + m.ID
}

// place checks that the model's GPU class exists in the profile and has enough GPUs per node.
func place(p *profile.Profile, m *models.Model) error {
	if !p.IsCloud() {
		if m.MinGPUClass != simulatorGPU {
			return fmt.Errorf("model %s needs GPU class %s; profile %s only has the fake %s node", m.ID, m.MinGPUClass, p.Metadata.Name, simulatorGPU)
		}
		return nil
	}
	for _, c := range p.Spec.AWS.GPUClasses {
		if c.Name != m.MinGPUClass {
			continue
		}
		most := 0
		for _, t := range c.InstanceTypes {
			if spec, ok := gpu.Instances[t]; ok && spec.GPUs > most {
				most = spec.GPUs
			}
		}
		if m.TensorParallelSize > most {
			return fmt.Errorf("model %s needs %d GPUs (tensor parallel size) but the largest %s instance type of profile %s has %d", m.ID, m.TensorParallelSize, c.Name, p.Metadata.Name, most)
		}
		return nil
	}
	return fmt.Errorf("model %s needs GPU class %s, which profile %s does not define", m.ID, m.MinGPUClass, p.Metadata.Name)
}

func flags(m *models.Model) models.RuntimeFlags {
	if m.RuntimeFlags != nil {
		return *m.RuntimeFlags
	}
	return models.RuntimeFlags{}
}

// source is the model location the runtime loads from, by loading method.
func source(m *models.Model) (string, error) {
	switch m.LoadMethod {
	case "s3-stream":
		return "s3://$(AIBOX_WEIGHTS_BUCKET)/" + m.Prefix(), nil
	case "nvme-cache":
		return "/models/" + m.ID, nil
	case "hf-download":
		return m.Source.Repo, nil
	default:
		return "", fmt.Errorf("load method %q needs weights", m.LoadMethod)
	}
}

func itoa(i int) string { return strconv.Itoa(i) }

func ftoa(f float64) string { return strconv.FormatFloat(f, 'f', -1, 64) }

func vllm(m *models.Model) (map[string]any, error) {
	src, err := source(m)
	if err != nil {
		return nil, err
	}
	f := flags(m)
	args := []any{src, "--served-model-name", m.ID, "--port", itoa(Port),
		"--tensor-parallel-size", itoa(m.TensorParallelSize), "--max-model-len", itoa(m.MaxModelLen),
		"--shutdown-timeout", itoa(m.GracePeriod() - drainMargin)}
	if f.GPUMemoryUtilization > 0 {
		args = append(args, "--gpu-memory-utilization", ftoa(f.GPUMemoryUtilization))
	}
	if f.MaxNumSeqs > 0 {
		args = append(args, "--max-num-seqs", itoa(f.MaxNumSeqs))
	}
	if f.KVCacheDtype != "" && f.KVCacheDtype != "auto" {
		args = append(args, "--kv-cache-dtype", f.KVCacheDtype)
	}
	if f.EnablePrefixCaching != nil {
		args = append(args, boolFlag("enable-prefix-caching", *f.EnablePrefixCaching))
	}
	if f.EnableChunkedPrefill != nil {
		args = append(args, boolFlag("enable-chunked-prefill", *f.EnableChunkedPrefill))
	}
	args = append(args, quantization(m)...)
	args = append(args, loadArgs(m)...)
	for _, a := range f.ExtraArgs {
		args = append(args, a)
	}
	return container(VLLMImage, []any{"vllm", "serve"}, args), nil
}

func sglang(m *models.Model) (map[string]any, error) {
	src, err := source(m)
	if err != nil {
		return nil, err
	}
	f := flags(m)
	args := []any{"-m", "sglang.launch_server", "--model-path", src, "--served-model-name", m.ID,
		"--host", "0.0.0.0", "--port", itoa(Port), "--tp-size", itoa(m.TensorParallelSize),
		"--context-length", itoa(m.MaxModelLen), "--enable-metrics"}
	if f.GPUMemoryUtilization > 0 {
		args = append(args, "--mem-fraction-static", ftoa(f.GPUMemoryUtilization))
	}
	if f.MaxNumSeqs > 0 {
		args = append(args, "--max-running-requests", itoa(f.MaxNumSeqs))
	}
	switch f.KVCacheDtype {
	case "", "auto":
	case "fp8":
		args = append(args, "--kv-cache-dtype", "fp8_e4m3")
	default:
		args = append(args, "--kv-cache-dtype", f.KVCacheDtype)
	}
	if f.EnablePrefixCaching != nil && !*f.EnablePrefixCaching {
		args = append(args, "--disable-radix-cache")
	}
	if f.EnableChunkedPrefill != nil && !*f.EnableChunkedPrefill {
		args = append(args, "--chunked-prefill-size", "-1")
	}
	args = append(args, quantization(m)...)
	args = append(args, loadArgs(m)...)
	for _, a := range f.ExtraArgs {
		args = append(args, a)
	}
	return container(SGLangImage, []any{"python3"}, args), nil
}

func simulator(m *models.Model) map[string]any {
	f := flags(m)
	seqs := f.MaxNumSeqs
	if seqs == 0 {
		seqs = 8
	}
	args := []any{"--model=" + m.ID, "--port=" + itoa(Port), "--mode=random", "--seed=42",
		"--max-num-seqs=" + itoa(seqs), "--max-model-len=" + itoa(m.MaxModelLen),
		"--time-to-first-token=200ms", "--inter-token-latency=20ms",
		"--enable-kvcache", "--kv-cache-size=1024", "--block-size=16"}
	c := container(SimulatorImage, []any{"/app/llm-d-inference-sim"}, args)
	c["env"] = append(c["env"].([]any),
		envField("POD_NAME", "metadata.name"), envField("POD_NAMESPACE", "metadata.namespace"), envField("POD_IP", "status.podIP"))
	c["resources"] = map[string]any{
		"requests": map[string]any{"cpu": "50m", "memory": "64Mi"},
		"limits":   map[string]any{"memory": "256Mi"},
	}
	c["readinessProbe"] = probe("/health/ready", 5, 3)
	c["startupProbe"] = probe("/health", 2, 30)
	return c
}

func boolFlag(name string, on bool) string {
	if on {
		return "--" + name
	}
	return "--no-" + name
}

func quantization(m *models.Model) []any {
	switch m.Quantization {
	case "fp8":
		return []any{"--quantization", "fp8"}
	case "awq":
		return []any{"--quantization", "awq_marlin"}
	case "bf16":
		return []any{"--dtype", "bfloat16"}
	case "fp16":
		return []any{"--dtype", "float16"}
	}
	return nil
}

func loadArgs(m *models.Model) []any {
	switch m.LoadMethod {
	case "s3-stream":
		return []any{"--load-format", "runai_streamer"}
	case "hf-download":
		return []any{"--revision", m.Source.Revision}
	}
	return nil
}

func container(image string, command, args []any) map[string]any {
	return map[string]any{
		"name":    "main",
		"image":   image,
		"command": command,
		"args":    args,
		"ports":   []any{map[string]any{"name": "http", "containerPort": Port, "protocol": "TCP"}},
		"env":     []any{},
		"livenessProbe": map[string]any{
			"httpGet": map[string]any{"path": "/health", "port": Port}, "periodSeconds": 10, "timeoutSeconds": 5, "failureThreshold": 3,
		},
		"readinessProbe": probe("/health", 5, 3),
	}
}

func probe(path string, period, failures int) map[string]any {
	return map[string]any{
		"httpGet":          map[string]any{"path": path, "port": Port},
		"periodSeconds":    period,
		"timeoutSeconds":   5,
		"failureThreshold": failures,
	}
}

func env(name, value string) map[string]any { return map[string]any{"name": name, "value": value} }

func envField(name, path string) map[string]any {
	return map[string]any{"name": name, "valueFrom": map[string]any{"fieldRef": map[string]any{"fieldPath": path}}}
}

func envRunConfig(name, key string) map[string]any {
	return map[string]any{"name": name, "valueFrom": map[string]any{"configMapKeyRef": map[string]any{
		"name": RunConfigMap, "key": key, "optional": true,
	}}}
}

// addGPU sets GPU, CPU and memory resources and a larger /dev/shm for tensor parallelism.
func addGPU(m *models.Model, c, pod map[string]any) {
	tp := m.TensorParallelSize
	gpus := itoa(tp)
	mem := itoa(memGiPerGPU*tp) + "Gi"
	c["resources"] = map[string]any{
		"requests": map[string]any{gpuResource: gpus, "cpu": itoa(cpuPerGPU * tp), "memory": mem},
		"limits":   map[string]any{gpuResource: gpus, "memory": mem},
	}
	if tp > 1 {
		pod["volumes"] = append(volumes(pod), map[string]any{
			"name": "dshm", "emptyDir": map[string]any{"medium": "Memory", "sizeLimit": itoa(shmGiPerGPU*tp) + "Gi"},
		})
	}
}

// addWarmup makes readiness follow a successful request (postStart hook) and sizes the
// startup probe for the model's load budget.
func addWarmup(m *models.Model, c map[string]any) {
	c["env"] = append(c["env"].([]any), env("AIBOX_MODEL_ID", m.ID), env("AIBOX_STARTUP_TIMEOUT", itoa(m.StartupTimeout())))
	c["lifecycle"] = map[string]any{"postStart": map[string]any{"exec": map[string]any{
		"command": []any{"python3", "-c", warmupScript},
	}}}
	c["startupProbe"] = probe("/health", 10, (m.StartupTimeout()+9)/10)
}

// addWeights wires the loading method: bucket and region from the run ConfigMap, an init
// container for nvme-cache, the optional Hugging Face token for hf-download.
func addWeights(m *models.Model, c, pod map[string]any) error {
	e := c["env"].([]any)
	switch m.LoadMethod {
	case "s3-stream":
		e = append(e, envRunConfig("AIBOX_WEIGHTS_BUCKET", "weightsBucket"), envRunConfig("AWS_REGION", "region"))
	case "nvme-cache":
		pod["initContainers"] = []any{fetchContainer(m)}
		pod["volumes"] = append(volumes(pod),
			map[string]any{"name": "fetch-scripts", "configMap": map[string]any{"name": FetchConfigMap}},
			map[string]any{"name": "fetch-work", "emptyDir": map[string]any{}})
	case "hf-download":
		e = append(e, map[string]any{"name": "HF_TOKEN", "valueFrom": map[string]any{"secretKeyRef": map[string]any{
			"name": TokenSecret, "key": "token", "optional": true,
		}}})
	default:
		return fmt.Errorf("load method %q is not supported by runtime %s", m.LoadMethod, m.Runtime)
	}
	c["env"] = e
	return nil
}

func volumes(pod map[string]any) []any {
	v, _ := pod["volumes"].([]any)
	return v
}

// fetchContainer copies the verified mirror into the model-cache volume of KServe's template
// (node ephemeral storage, backed by the instance store on GPU nodes).
func fetchContainer(m *models.Model) map[string]any {
	script := "set -eu\n" +
		"mkdir -p \"$HOME\" \"$TMPDIR\"\n" +
		"python -m pip install --quiet --require-hashes --only-binary=:all: --target /work/py -r /scripts/requirements.txt\n" +
		"PYTHONPATH=/work/py exec python /scripts/mirror.py fetch\n"
	return map[string]any{
		"name":    "fetch-weights",
		"image":   models.Image,
		"command": []any{"/bin/sh", "-c", script},
		"env": []any{
			envRunConfig("BUCKET", "weightsBucket"), envRunConfig("AWS_REGION", "region"),
			env("PREFIX", m.Prefix()), env("DEST", "/models/"+m.ID),
			env("HOME", "/work/home"), env("TMPDIR", "/work/tmp"),
			env("PYTHONDONTWRITEBYTECODE", "1"), env("PIP_DISABLE_PIP_VERSION_CHECK", "1"), env("PIP_NO_CACHE_DIR", "1"),
		},
		"securityContext": map[string]any{
			"allowPrivilegeEscalation": false, "readOnlyRootFilesystem": true,
			"capabilities": map[string]any{"drop": []any{"ALL"}},
		},
		"volumeMounts": []any{
			map[string]any{"name": "model-cache", "mountPath": "/models"},
			map[string]any{"name": "fetch-scripts", "mountPath": "/scripts", "readOnly": true},
			map[string]any{"name": "fetch-work", "mountPath": "/work"},
		},
	}
}

// fetchScripts is the ConfigMap with mirror.py for nvme-cache init containers.
func fetchScripts() (map[string]any, error) {
	cm, err := models.Scripts()
	if err != nil {
		return nil, err
	}
	return map[string]any{
		"apiVersion": "v1",
		"kind":       "ConfigMap",
		"metadata": map[string]any{"name": FetchConfigMap, "namespace": Namespace,
			"labels": map[string]any{"app.kubernetes.io/part-of": "aibox"}},
		"data": map[string]any{"mirror.py": cm.Data["mirror.py"], "requirements.txt": cm.Data["requirements.txt"]},
	}, nil
}
