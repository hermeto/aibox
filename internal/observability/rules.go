// Package observability generates AIBox's Prometheus rules (feature 010): canonical runtime
// series from metrics/runtime-metrics.yaml (so dashboards and alerts work for vLLM and
// SGLang), live cost from the price table, SLO alerts from the catalog and the platform alerts.
// Rules render as a PrometheusRule for the cluster and as a plain rule file for promtool.
package observability

import (
	"fmt"
	"math"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"sigs.k8s.io/yaml"

	"github.com/hermeto/aibox/internal/cost"
	"github.com/hermeto/aibox/internal/models"
	"github.com/hermeto/aibox/internal/profile"
)

// Header is written at the top of generated files.
const Header = "# Generated by `aibox render rules` from metrics/runtime-metrics.yaml, data/pricing, models/catalog.yaml and profiles/%s.yaml — do not edit.\n# Regenerate with `make generate`; CI fails on drift.\n"

// Namespace of the observability component (PrometheusRule, monitors, Grafana).
const Namespace = "observability"

// Mapping is metrics/runtime-metrics.yaml.
type Mapping struct {
	APIVersion string            `json:"apiVersion"`
	Kind       string            `json:"kind"`
	Runtimes   map[string]string `json:"runtimes"`
	Metrics    []Metric          `json:"metrics"`
}

// Metric maps one canonical metric to the runtimes' names.
type Metric struct {
	Name   string `json:"name"`
	Type   string `json:"type"`
	Help   string `json:"help"`
	VLLM   string `json:"vllm"`
	SGLang string `json:"sglang"`
}

// LoadMapping reads metrics/runtime-metrics.yaml under root.
func LoadMapping(root string) (*Mapping, error) {
	data, err := os.ReadFile(filepath.Join(root, "metrics", "runtime-metrics.yaml")) //nolint:gosec // repository file
	if err != nil {
		return nil, err
	}
	var m Mapping
	if err := yaml.UnmarshalStrict(data, &m); err != nil {
		return nil, fmt.Errorf("metrics/runtime-metrics.yaml: %w", err)
	}
	return &m, nil
}

// Rule is one Prometheus recording or alerting rule.
type Rule struct {
	Record      string            `json:"record,omitempty"`
	Alert       string            `json:"alert,omitempty"`
	Expr        string            `json:"expr"`
	For         string            `json:"for,omitempty"`
	Labels      map[string]string `json:"labels,omitempty"`
	Annotations map[string]string `json:"annotations,omitempty"`
}

// Group is a rule group.
type Group struct {
	Name     string `json:"name"`
	Interval string `json:"interval,omitempty"`
	Rules    []Rule `json:"rules"`
}

// byModel normalizes a runtime series to the labels AIBox aggregates on (model, namespace):
// both runtimes label their series with the served model name (`model_name`), which AIBox
// sets to the catalog id.
func byModel(agg, series, extra string) string {
	by := "namespace, model"
	if extra != "" {
		by += ", " + extra
	}
	return fmt.Sprintf(`%s by (%s) (label_replace(%s, "model", "$1", "model_name", "(.*)"))`, agg, by, series)
}

// either combines the vLLM and SGLang expressions of one canonical series.
func either(m Metric, f func(name string) string) string {
	var parts []string
	for _, n := range []string{m.VLLM, m.SGLang} {
		if n != "" {
			parts = append(parts, f(n))
		}
	}
	return strings.Join(parts, " or ")
}

// Quantiles recorded for every canonical histogram.
var Quantiles = []string{"50", "95", "99"}

// RuntimeGroup records canonical series: gauges per model (ratios averaged over replicas,
// counts summed), counters and histogram buckets as 1-minute rates, plus p50/p95/p99 for
// histograms. Model servers are scraped every 15 s, so a 1-minute window holds 4 samples.
func RuntimeGroup(m *Mapping) Group {
	g := Group{Name: "aibox-runtime", Interval: "15s"}
	for _, e := range m.Metrics {
		switch e.Type {
		case "gauge":
			agg := "sum"
			if strings.HasSuffix(e.Name, "_ratio") {
				agg = "avg"
			}
			g.Rules = append(g.Rules, Rule{Record: "aibox:" + e.Name, Expr: either(e, func(n string) string {
				return byModel(agg, n, "")
			})})
		case "counter":
			g.Rules = append(g.Rules, Rule{Record: "aibox:" + e.Name + ":rate1m", Expr: either(e, func(n string) string {
				return byModel("sum", "rate("+n+"[1m])", "")
			})})
		case "histogram":
			bucket := "aibox:" + e.Name + "_bucket:rate1m"
			g.Rules = append(g.Rules, Rule{Record: bucket, Expr: either(e, func(n string) string {
				return byModel("sum", "rate("+n+"_bucket[1m])", "le")
			})})
			for _, q := range Quantiles {
				g.Rules = append(g.Rules, Rule{
					Record: "aibox:" + e.Name + ":p" + q,
					Expr:   fmt.Sprintf("histogram_quantile(0.%s, sum by (namespace, model, le) (%s))", q, bucket),
				})
			}
		}
	}
	return g
}

// NodeLabels joins kube-state-metrics node labels (allow-listed in the kube-prometheus-stack
// values) into instance_type, capacity_type and pool. Managed node group nodes (the system
// pool, on-demand) carry no Karpenter capacity type and count as on-demand; Karpenter's
// "reserved" is a capacity block. The pool is the Karpenter NodePool, else the node group.
const NodeLabels = `label_replace(label_replace(label_replace(label_replace(label_replace(label_replace(kube_node_labels, ` +
	`"instance_type", "$1", "label_node_kubernetes_io_instance_type", "(.+)"), ` +
	`"capacity_type", "$1", "label_karpenter_sh_capacity_type", "(.+)"), ` +
	`"capacity_type", "on-demand", "capacity_type", ""), ` +
	`"capacity_type", "capacity-block", "capacity_type", "reserved"), ` +
	`"pool", "$1", "label_eks_amazonaws_com_nodegroup", "(.+)"), ` +
	`"pool", "$1", "label_karpenter_sh_nodepool", "(.+)")`

// Capacities priced for every instance type (Karpenter's capacity types, "reserved" renamed).
var Capacities = []string{"on-demand", "spot", "capacity-block"}

// CostGroup turns the price table into cost series: the price of every instance type and
// capacity type, each node's price, USD per hour per pool and for the cluster (plus the fixed
// items), each model's share of its GPU nodes (by requested GPUs) and USD per 1M output
// tokens per model and for the whole cluster.
func CostGroup(t *cost.Table) Group {
	g := Group{Name: "aibox-cost", Interval: "1m"}
	types := make([]string, 0, len(t.Instances))
	for it := range t.Instances {
		types = append(types, it)
	}
	sort.Strings(types)
	for _, it := range types {
		for _, capacity := range Capacities {
			price, _ := t.Hourly(it, capacity)
			g.Rules = append(g.Rules, Rule{
				Record: "aibox:instance_price_usd_per_hour",
				Expr:   fmt.Sprintf("vector(%g)", price),
				Labels: map[string]string{"instance_type": it, "capacity_type": capacity},
			})
		}
	}
	names := make([]string, 0, len(t.Fixed))
	for n := range t.Fixed {
		names = append(names, n)
	}
	sort.Strings(names)
	var fixed float64
	for _, n := range names {
		fixed += t.Fixed[n]
	}
	fixed = math.Round(fixed*1e6) / 1e6 // no float noise in the generated files
	g.Rules = append(g.Rules,
		Rule{Record: "aibox:node_price_usd_per_hour", Expr: "max by (node, instance_type, capacity_type, pool) (" + NodeLabels +
			") * on (instance_type, capacity_type) group_left () aibox:instance_price_usd_per_hour"},
		Rule{Record: "aibox:pool_cost_usd_per_hour", Expr: "sum by (pool) (aibox:node_price_usd_per_hour)"},
		Rule{Record: "aibox:cluster_cost_usd_per_hour", Expr: fmt.Sprintf("sum(aibox:node_price_usd_per_hour) + %g", fixed)},
		Rule{Record: "aibox:pod_gpu_share", Expr: `sum by (namespace, pod, node) (kube_pod_container_resource_requests{resource="nvidia_com_gpu"})` +
			` / on (node) group_left () sum by (node) (kube_node_status_allocatable{resource="nvidia_com_gpu"})`},
		Rule{Record: "aibox:model_cost_usd_per_hour", Expr: `sum by (namespace, model) (label_replace(aibox:pod_gpu_share` +
			` * on (namespace, pod) group_left (label_aibox_dev_model) max by (namespace, pod, label_aibox_dev_model) (kube_pod_labels{label_aibox_dev_model!=""}),` +
			` "model", "$1", "label_aibox_dev_model", "(.+)") * on (node) group_left () max by (node) (aibox:node_price_usd_per_hour))`},
		Rule{Record: "aibox:usd_per_million_output_tokens",
			Expr: "aibox:model_cost_usd_per_hour / on (namespace, model) (aibox:generation_tokens_total:rate1m * 3600 > 0) * 1e6"},
		Rule{Record: "aibox:cluster_usd_per_million_output_tokens",
			Expr: "aibox:cluster_cost_usd_per_hour / (sum(aibox:generation_tokens_total:rate1m) * 3600 > 0) * 1e6"},
	)
	return g
}

// Alert thresholds (product spec): KV cache above 90% for 5 minutes, pods pending for
// 5 minutes, a GPU node idle for 30 minutes, the TTFT p99 above the catalog target for 10.
const (
	KVCacheThreshold = 0.9
	SLOFor           = "10m"
)

// AlertGroup holds one TTFT SLO alert per served model (target from the catalog) and the
// platform alerts; cloud profiles also warn about instance types missing from the price table.
func AlertGroup(ms []models.Model, withCost bool) Group {
	g := Group{Name: "aibox-alerts"}
	for _, m := range ms {
		if !m.Served() {
			continue
		}
		g.Rules = append(g.Rules, Rule{
			Alert:  "AIBoxTTFTSLOViolation",
			Expr:   fmt.Sprintf(`aibox:time_to_first_token_seconds:p99{model=%q} > %g`, m.ID, float64(m.SLO.TTFTP99Ms)/1000),
			For:    SLOFor,
			Labels: map[string]string{"severity": "warning", "model": m.ID},
			Annotations: map[string]string{
				"summary":     fmt.Sprintf("TTFT p99 of %s above its %d ms target", m.ID, m.SLO.TTFTP99Ms),
				"description": "TTFT p99 is {{ $value | humanizeDuration }} in {{ $labels.namespace }} (target from models/catalog.yaml).",
			},
		})
	}
	g.Rules = append(g.Rules,
		Rule{Alert: "AIBoxKVCacheSaturated", Expr: fmt.Sprintf("aibox:kv_cache_usage_ratio > %g", KVCacheThreshold), For: "5m",
			Labels: map[string]string{"severity": "warning"},
			Annotations: map[string]string{
				"summary":     "KV cache of {{ $labels.model }} above 90% for 5 minutes",
				"description": "KV-cache usage is {{ $value | humanizePercentage }}; requests queue and get preempted. Add replicas or lower max sequences.",
			}},
		Rule{Alert: "AIBoxPodsPending", Expr: `sum by (namespace, pod) (kube_pod_status_phase{phase="Pending"}) > 0`, For: "5m",
			Labels: map[string]string{"severity": "warning"},
			Annotations: map[string]string{
				"summary":     "{{ $labels.namespace }}/{{ $labels.pod }} pending for more than 5 minutes",
				"description": "Check capacity (Karpenter NodeClaims, GPU quotas) and the pod's events.",
			}},
		Rule{Alert: "AIBoxGPUNodeIdle", Expr: "max by (node) (DCGM_FI_DEV_GPU_UTIL) == 0", For: "30m",
			Labels: map[string]string{"severity": "info"},
			Annotations: map[string]string{
				"summary":     "GPU node {{ $labels.node }} idle for 30 minutes",
				"description": "No GPU on the node did any work for 30 minutes; it still costs money.",
			}},
	)
	if withCost {
		g.Rules = append(g.Rules, Rule{
			Alert: "AIBoxPriceMissing",
			Expr:  "count by (instance_type, capacity_type) (" + NodeLabels + " unless on (instance_type, capacity_type) aibox:instance_price_usd_per_hour) > 0",
			For:   "10m", Labels: map[string]string{"severity": "warning"},
			Annotations: map[string]string{
				"summary":     "No price for {{ $labels.instance_type }} ({{ $labels.capacity_type }}): cost series are incomplete",
				"description": "Add the instance type to data/pricing and run `make generate`.",
			},
		})
	}
	return g
}

// Groups returns every generated group for a profile (cost only when prices are given).
func Groups(p *profile.Profile, c *models.Catalog, m *Mapping, prices *cost.Table) ([]Group, error) {
	sel, err := c.Select(p.Metadata.Name, false, nil)
	if err != nil {
		return nil, err
	}
	sort.Slice(sel, func(i, j int) bool { return sel[i].ID < sel[j].ID })
	groups := []Group{RuntimeGroup(m)}
	if prices != nil {
		groups = append(groups, CostGroup(prices))
	}
	return append(groups, AlertGroup(sel, prices != nil)), nil
}

// Build loads the runtime mapping and, for cloud profiles, the region's price table under the
// repository root, and returns the profile's groups.
func Build(root string, p *profile.Profile, c *models.Catalog) ([]Group, error) {
	m, err := LoadMapping(root)
	if err != nil {
		return nil, err
	}
	var prices *cost.Table
	if p.IsCloud() {
		if prices, err = cost.LoadTable(root, p.Spec.AWS.Region); err != nil {
			return nil, err
		}
	}
	return Groups(p, c, m, prices)
}

// PrometheusRule wraps the groups for the Prometheus Operator.
func PrometheusRule(groups []Group) map[string]any {
	return map[string]any{
		"apiVersion": "monitoring.coreos.com/v1",
		"kind":       "PrometheusRule",
		"metadata": map[string]any{
			"name":      "aibox",
			"namespace": Namespace,
			"labels":    map[string]any{"app.kubernetes.io/part-of": "aibox"},
		},
		"spec": map[string]any{"groups": groups},
	}
}

// Formats accepted by Render.
const (
	FormatK8s        = "k8s"
	FormatPrometheus = "prometheus"
)

// Render writes the PrometheusRule (FormatK8s) or a plain rule file (FormatPrometheus).
func Render(p *profile.Profile, groups []Group, format string) ([]byte, error) {
	var obj any
	switch format {
	case FormatK8s:
		obj = PrometheusRule(groups)
	case FormatPrometheus:
		obj = map[string]any{"groups": groups}
	default:
		return nil, fmt.Errorf("unknown rule format %q (want %s or %s)", format, FormatK8s, FormatPrometheus)
	}
	b, err := yaml.Marshal(obj)
	if err != nil {
		return nil, err
	}
	return append([]byte(fmt.Sprintf(Header, p.Metadata.Name)), b...), nil
}
